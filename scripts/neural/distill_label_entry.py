def _file_sha256(path: Path) -> str:
    digest = sha256()
    with Path(path).open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def checkpoint_sha256(path: Path) -> dict:
    """Every file of a checkpoint directory and the hash of that listing."""
    path = Path(path)
    if not path.is_dir():
        raise ValueError(f"mixed checkpoint {path} is not a checkpoint directory")
    files = {child.name: _file_sha256(child) for child in sorted(path.iterdir()) if child.is_file()}
    return {"sha256": content_sha256(files), "files": files}


def check_roundtrip(reader, expected) -> int:
    """Each ``(row, digest)``: the stored row must expand to the Gym frame with that ``frame_digest``."""
    for row, digest in expected:
        stored = reader.frame(row)
        if frame_digest(stored.schema_fingerprint, stored.tensors) != digest:
            raise RoundTripError(f"shard {reader.path.name} row {row} does not expand to the Gym's observation")
    return len(expected)


def _learner_state() -> dict:
    """The learner revision and dirty state: the runtime runner's record, else git."""
    runner = os.environ.get("SPIRE_LEARN_RUNNER_OUTPUT")
    if runner and (Path(runner) / "manifest.json").is_file():
        learner = json.loads((Path(runner) / "manifest.json").read_text())["learner"]
        dirty = learner["dirty"]
        return {"revision": learner["head"], "dirty": bool(dirty), "dirty_paths": dirty, "source": "runner"}
    head = subprocess.run(["git", "-C", str(_ROOT), "rev-parse", "HEAD"], capture_output=True, text=True,
                          check=True, timeout=30).stdout.strip()
    status = subprocess.run(["git", "-C", str(_ROOT), "status", "--porcelain=v1"], capture_output=True, text=True,
                            check=True, timeout=30).stdout.splitlines()
    return {"revision": head, "dirty": bool(status), "dirty_paths": sorted(status), "source": "git"}


def _empty_counts() -> dict:
    return {
        "fights": dict.fromkeys(FIGHT_TYPES, 0), "fights_by_series": dict.fromkeys(SERIES, 0),
        "decisions": dict.fromkeys(FIGHT_TYPES, 0), "rows": dict.fromkeys(SERIES, 0),
        "rows_by_fight_type": dict.fromkeys(FIGHT_TYPES, 0), "value_rows": 0,
        "roots": {"searched": 0, "single_legal": 0, "refused": 0}, "refusal_classes": {},
        "outcomes": {kind: {} for kind in FIGHT_TYPES},
        "censored": {cap: {kind: {"fights": 0, "kept": 0, "dropped": 0} for kind in FIGHT_TYPES} for cap in CAPS},
        "all_tie": {"rows": 0, "searched_rows": 0, "share": None}, "roundtrips": 0, "player_moves": 0,
    }


def _count(counts: dict, result: dict) -> None:
    kind, rows = result["fight_type"], len(result["rows"])
    counts["fights"][kind] += 1
    counts["fights_by_series"][result["series"]] += 1
    counts["decisions"][kind] += result["decisions"]
    counts["rows"][result["series"]] += rows
    counts["rows_by_fight_type"][kind] += rows
    counts["value_rows"] += sum(labels.value_ok for _, labels, _ in result["rows"])
    for root, n in result["roots"].items():
        counts["roots"][root] += n
    for refusal, n in result["refusals"].items():
        counts["refusal_classes"][refusal] = counts["refusal_classes"].get(refusal, 0) + n
    outcomes = counts["outcomes"][kind]
    outcomes[result["outcome"]] = outcomes.get(result["outcome"], 0) + 1
    if result["censor_reason"] is not None:
        cell = counts["censored"][result["censor_reason"]][kind]
        cell["fights"] += 1
        cell["kept"] += rows
        cell["dropped"] += result["dropped"]
    counts["all_tie"]["rows"] += result["all_tie"]
    counts["all_tie"]["searched_rows"] += result["roots"].get("searched", 0)
    counts["player_moves"] += result["player_moves"]


def _write_json_atomic(path: Path, document) -> None:
    temporary = path.with_name(f".{path.name}.tmp-{os.getpid()}")
    with temporary.open("x", encoding="utf-8") as handle:
        json.dump(document, handle, indent=1, sort_keys=True, allow_nan=False)
        handle.write("\n")
        handle.flush()
        os.fsync(handle.fileno())
    os.rename(temporary, path)


def _check_gym(recipe, teacher):
    """The live Gym's build, revision and contract, checked as the teacher entry checks them."""
    from spire_lab import _native
    from spire_learn.neural.gym_contracts import STANDARD_COMPACT_PRESET, accepts_recorded_revision, contract_for_revision
    from spire_learn.neural.search_one_move import require_tiered_playouts
    from spire_learn.neural.standard_stream import StandardRecipe

    if not isinstance(recipe, StandardRecipe):
        raise ValueError("Labelling requires a Standard recipe")
    gym_build = dict(_native.build_info())
    live_revision = gym_build.get("revision")
    revision = contract_for_revision(recipe.gym_revision).source_revision
    if not accepts_recorded_revision(live_revision, revision):
        raise ValueError(f"Labelling requires Gym revision {revision} or one in its rules epoch")
    live = contract_for_revision(live_revision)
    if STANDARD_COMPACT_PRESET not in live.standard_compact_fingerprints:
        raise ValueError("Labelling requires a Gym with compact Standard views")
    _, playout_policy = entry._value_options(teacher)
    if entry._native_backend(teacher) and playout_policy != "uniform-v1":
        require_tiered_playouts(live)
    mapping = live.raw_mode_mappings_for_view(
        live.standard_compact_fingerprints[STANDARD_COMPACT_PRESET])["standard-standalone"]
    return gym_build, live_revision, live, mapping


def run_chunk(args, output: Path) -> dict:
    from spire_learn.neural.distill_data import ShardReader, ShardWriter, decode_decision, validation_runs
    from spire_learn.neural.gym_contracts import STANDARD_COMPACT_PRESET
    from spire_learn.neural.recipes import gym_validator, load_recipe
    from spire_learn.neural.schema import parse_combat_descriptor
    from spire_learn.neural.standard_stream import generate_standard_shard, levels_for_shard

    wall_start = perf_counter()
    teacher, teacher_sha, calibrated = entry._teacher(args.teachers, args.teacher, None)
    if not calibrated and not args.allow_uncalibrated:
        raise ValueError(f"{args.teacher} is uncalibrated; pass --allow-uncalibrated")
    rule, playout_policy = entry._value_options(teacher)
    if rule.name != "resource-v2":
        raise ValueError("distillation labels need a resource-v2 teacher")
    recipe = load_recipe(args.recipe)
    gym_build, live_revision, live, mapping = _check_gym(recipe, teacher)
    mixed = checkpoint_sha256(args.mixed_checkpoint) if args.mixed_every else None

    first, count = args.shards
    holdout = validation_runs(state["run_id"] for state in recipe.states if run_split(state["run_id"]) == "train")
    shards = [generate_standard_shard(recipe, split="train", shard_index=index,
                                      validate=gym_validator(recipe=recipe) if max(levels_for_shard(recipe, index))
                                      else None)
              for index in range(first, first + count)]
    jobs = plan_jobs(shards, holdout, seed=args.seed, mixed_every=args.mixed_every, case_limit=args.case_limit)
    if not jobs:
        raise ValueError("No fights selected")
    descriptor = entry.preflight([job.case for job in jobs], "train")
    schema = parse_combat_descriptor(descriptor, revision=live_revision)

    provenance = {
        "label_schema": CHUNK_SCHEMA, "teacher": args.teacher, "config_sha256": teacher_sha,
        "teacher_config": entry._teacher_config(teacher), "teachers_sha256": _file_sha256(args.teachers),
        "calibrated": calibrated, **({"uncalibrated_allowed": True} if args.allow_uncalibrated else {}),
        "recipe_sha256": _file_sha256(args.recipe), "states_table_sha256": recipe.table_sha256,
        "gym_revision": live_revision, "rules_epoch": live.rules_epoch, "capacity_preset": STANDARD_COMPACT_PRESET,
        "seed": args.seed, "research_seed_rule": "H(seed, shard, local); decision: (fight seed * 1024 + step) mod 2**64",
        "mixed_seed_rule": "H(seed, 'mixed', shard, local)", "seed_hash": "first 16 hex digits of content_sha256",
        "mixed_every": args.mixed_every, "mixed_rule": "(shard * 256 + local) % mixed_every == mixed_every - 1",
        "mixed_checkpoint_sha256": None if mixed is None else mixed["sha256"],
        "mixed_model_config": None if mixed is None else asdict(MIXED_MODEL_CONFIG),
        "turn_cap": TURN_CAP, "fight_cap": FIGHT_CAP, "kept_prefix_max": KEPT_PREFIX_MAX,
        "roundtrip_every": args.roundtrip_every, "case_limit": args.case_limit,
        "holdout_runs": len(holdout), "holdout_sha256": content_sha256(sorted(holdout)),
    }
    context = LabelContext(teacher=teacher, gym_revision=live_revision, schema_fingerprint=schema.schema_fingerprint,
                           mixed_checkpoint=None if mixed is None else str(args.mixed_checkpoint),
                           mixed_mapping=mapping if mixed else None)

    output.mkdir(parents=True)
    remaining = Counter(job.shard for job in jobs)
    open_shards: dict = {}
    written = {series: {} for series in SERIES}
    counts = _empty_counts()
    fight_cpu = fight_wall = 0.0
    fight_timings = []

    def writers(index):
        if index not in open_shards:
            open_shards[index] = {series: {
                "writer": ShardWriter(output / series / shard_name(index), schema,
                                      {**provenance, "series": series, "shard_index": index}),
                "rows": 0, "roundtrip": []} for series in SERIES}
        return open_shards[index]

    def close(index):
        for series, state in writers(index).items():
            path = output / series / shard_name(index)
            manifest = state["writer"].close()
            with ShardReader(path, schema) as reader:
                reader.verify()
                counts["roundtrips"] += check_roundtrip(reader, state["roundtrip"])
            written[series][shard_name(index)] = {
                "rows": manifest["rows"], "manifest_sha256": _file_sha256(path / "manifest.json")}
        del open_shards[index]

    pending_close = list(range(first, first + count))
    for result in _results([(job, context) for job in jobs], args.parallel):
        state = writers(result["shard"])[result["series"]]
        for arrays, labels, digest in result["rows"]:
            if state["rows"] % args.roundtrip_every == 0:  # row r of the shard, independent of chunking
                state["roundtrip"].append((state["rows"], digest))
            state["writer"].add(decode_decision(arrays, schema), labels)
            state["rows"] += 1
        _count(counts, result)
        fight_cpu += result["cpu_seconds"]
        fight_wall += result["wall_seconds"]
        fight_timings.append({
            "shard": result["shard"], "local": result["local"], "series": result["series"],
            "fight_type": result["fight_type"], "outcome": result["outcome"],
            "censor_reason": result["censor_reason"], "decisions": result["decisions"],
            "cpu_seconds": result["cpu_seconds"], "wall_seconds": result["wall_seconds"]})
        remaining[result["shard"]] -= 1
        while pending_close and remaining[pending_close[0]] == 0:
            close(pending_close.pop(0))
    while pending_close:  # shards whose every case was skipped by the generator
        close(pending_close.pop(0))
    searched = counts["all_tie"]["searched_rows"]
    counts["all_tie"]["share"] = counts["all_tie"]["rows"] / searched if searched else None

    manifest = {
        "schema": CHUNK_SCHEMA, "first_shard": first, "shard_count": count,
        "observation": {"schema_id": schema.schema_id, "schema_fingerprint": schema.schema_fingerprint,
                        "descriptor_digest": schema.descriptor_digest, "gym_revision": schema.gym_revision},
        "shards": written, "counts": counts,
        "provenance": {**provenance, "gym_build": gym_build, "learner": _learner_state(),
                       "mixed_checkpoint": mixed, "environment": "train", "split": "train",
                       "character": recipe.character, "ascension": recipe.ascension,
                       "profile": descriptor["profile_id"]},
    }
    _write_json_atomic(output / REPORT, {
        "schema": "spire-learn-distill-label-report-v2", "parallel": args.parallel,
        "fight_cpu_seconds": fight_cpu, "fight_wall_seconds": fight_wall,
        "run_wall_seconds": perf_counter() - wall_start, "gpu_seconds": 0,
        "searched_rows": searched, "fights": sum(counts["fights"].values()),
        "fight_timings": sorted(fight_timings, key=lambda row: (row["shard"], row["local"]))})
    _write_json_atomic(output / CHUNK_MANIFEST, manifest)
    return manifest


def chunk_expectation(*, first_shard, shard_count, seed, teacher, config_sha256, recipe_sha256,
                      states_table_sha256, mixed_checkpoint_sha256, mixed_every, roundtrip_every,
                      gym_revision, rules_epoch, case_limit=None) -> dict:
    """What a driver means to produce for one chunk (``case_limit`` stays None for real labels)."""
    return dict(first_shard=first_shard, shard_count=shard_count, seed=seed, teacher=teacher,
                config_sha256=config_sha256, recipe_sha256=recipe_sha256, states_table_sha256=states_table_sha256,
                mixed_checkpoint_sha256=mixed_checkpoint_sha256, mixed_every=mixed_every,
                roundtrip_every=roundtrip_every, case_limit=case_limit, gym_revision=gym_revision,
                rules_epoch=rules_epoch)


def _check_provenance(what, provenance, expected):
    for key in EXPECTED_PROVENANCE:
        if key not in provenance or provenance[key] != expected[key]:
            raise ChunkError(f"{what} {key} is {provenance.get(key)!r}, expected {expected[key]!r}")


def verify_chunk(path: Path, expected) -> dict:
    """A finished chunk's manifest, once it holds exactly what ``expected`` describes (stdlib only, no numpy).

    ``expected`` (see ``chunk_expectation``) names every key of ``EXPECTED_KEYS``. The chunk and every shard
    must record that range and provenance, every shard file must match its hash, and the chunk's per-shard
    rows and row counts must agree with the shard manifests.
    """
    path = Path(path)
    if set(expected) != set(EXPECTED_KEYS):
        raise ValueError(f"expected must name exactly {sorted(EXPECTED_KEYS)}")
    try:
        manifest = json.loads((path / CHUNK_MANIFEST).read_text())
        if manifest.get("schema") != CHUNK_SCHEMA:
            raise ChunkError("not a distillation label chunk")
        start, size = manifest["first_shard"], manifest["shard_count"]
        if (start, size) != (expected["first_shard"], expected["shard_count"]):
            raise ChunkError(f"chunk covers shards {start}:{size}, expected "
                             f"{expected['first_shard']}:{expected['shard_count']}")
        _check_provenance("chunk", manifest["provenance"], expected)
        names = [shard_name(index) for index in range(start, start + size)]
        counts = manifest["counts"]
        for series in SERIES:
            shards = manifest["shards"][series]
            if set(shards) != set(names) or {p.name for p in (path / series).iterdir()} != set(names):
                raise ChunkError(f"{series} series does not hold exactly the chunk's shards")
            for index, name in zip(range(start, start + size), names):
                item, directory = shards[name], path / series / name
                if _file_sha256(directory / "manifest.json") != item["manifest_sha256"]:
                    raise ChunkError(f"{series}/{name} manifest fails its sha256")
                shard = json.loads((directory / "manifest.json").read_text())
                _check_provenance(f"{series}/{name}", shard["provenance"], expected)
                if (shard["provenance"].get("series"), shard["provenance"].get("shard_index")) != (series, index):
                    raise ChunkError(f"{series}/{name} records another series or shard index")
                if shard["rows"] != item["rows"]:
                    raise ChunkError(f"{series}/{name} holds {shard['rows']} rows, the chunk records {item['rows']}")
                files = shard["files"]
                if {p.name for p in directory.iterdir()} != {"manifest.json", *(f"{n}.npy" for n in files)}:
                    raise ChunkError(f"{series}/{name} files differ from its manifest")
                for file, entry_ in files.items():
                    if _file_sha256(directory / f"{file}.npy") != entry_["sha256"]:
                        raise ChunkError(f"{series}/{name}/{file} fails its sha256")
            if sum(shards[name]["rows"] for name in names) != counts["rows"][series]:
                raise ChunkError(f"{series} shard rows disagree with the chunk's row count")
        total = sum(counts["rows"].values())
        if (sum(counts["rows_by_fight_type"].values()) != total or sum(counts["roots"].values()) != total
                or counts["fights"] != {kind: counts["fights"][kind] for kind in FIGHT_TYPES}
                or sum(counts["fights"].values()) != sum(counts["fights_by_series"].values())):
            raise ChunkError("chunk counts are inconsistent")
    except (OSError, ValueError, KeyError, TypeError, AttributeError) as error:
        if isinstance(error, ChunkError):
            raise
        raise ChunkError(f"chunk {path} fails verification: {error}") from None
    return manifest


# --- CLI -----------------------------------------------------------------------------------

def _shards(text):
    first, sep, count = text.partition(":")
    if not sep or not first.isdigit() or not count.isdigit() or int(count) < 1:
        raise argparse.ArgumentTypeError("must be FIRST:COUNT with COUNT >= 1")
    if int(first) < LABEL_SHARD_START:
        raise argparse.ArgumentTypeError(f"labelling starts at shard {LABEL_SHARD_START}")
    return int(first), int(count)


def _non_negative(value):
    number = int(value)
    if number < 0:
        raise argparse.ArgumentTypeError("must be non-negative")
    return number


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--recipe", type=Path, required=True)
    parser.add_argument("--teacher", required=True, help="a teacher name in --teachers (current-v2)")
    parser.add_argument("--teachers", type=Path, required=True)
    parser.add_argument("--allow-uncalibrated", action="store_true",
                        help="label with a teacher marked uncalibrated (recorded in provenance)")
    parser.add_argument("--shards", type=_shards, required=True, metavar="FIRST:COUNT")
    parser.add_argument("--seed", type=int, required=True)
    parser.add_argument("--mixed-checkpoint", type=Path, help="checkpoint directory of the mixed-fight player")
    parser.add_argument("--mixed-every", type=_non_negative, default=MIXED_EVERY)
    parser.add_argument("--output", type=Path, required=True, help=f"a fresh chunk directory under {OUTPUT_ROOT}/")
    parser.add_argument("--parallel", type=entry._positive, default=1)
    parser.add_argument("--roundtrip-every", type=entry._positive, default=ROUNDTRIP_EVERY)
    parser.add_argument("--case-limit", type=entry._positive,
                        help="label only the first N cases of each shard (smoke tests; recorded)")
    args = parser.parse_args(argv)

    output = (_ROOT / args.output).resolve()
    if not output.is_relative_to((_ROOT / OUTPUT_ROOT).resolve()):
        parser.error(f"--output must resolve under {OUTPUT_ROOT}/")
    expected = os.environ.get("SPIRE_LEARN_RUNNER_OUTPUT")
    if expected and not output.is_relative_to(Path(expected).resolve()):
        parser.error("--output must be inside SPIRE_LEARN_RUNNER_OUTPUT")
    if output.exists() or output.is_symlink():
        parser.error("--output already exists; each chunk is written to a fresh directory")
    if not 0 <= args.seed < 1 << 64:
        parser.error("--seed must be an unsigned 64-bit integer")
    if args.mixed_every and args.mixed_checkpoint is None:
        parser.error("--mixed-checkpoint is required when --mixed-every is positive")
    if not args.mixed_every and args.mixed_checkpoint is not None:
        parser.error("--mixed-checkpoint needs a positive --mixed-every")
    args.recipe, args.teachers = _ROOT / args.recipe, _ROOT / args.teachers
    if args.mixed_checkpoint is not None:
        args.mixed_checkpoint = (_ROOT / args.mixed_checkpoint).resolve()
    # Spawned workers inherit these before any numeric library starts its thread pools.
    os.environ.update(dict.fromkeys(_THREAD_VARIABLES, "1"))
    manifest = run_chunk(args, output)
    print(json.dumps({"output": str(output), "counts": manifest["counts"]}, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
