class RoundTripError(RuntimeError):
    """A stored decision does not expand to the compact observation the Gym returned."""


class ChunkError(ValueError):
    """A chunk directory is incomplete or fails its manifest."""


def derive_seed(*parts) -> int:
    """``H(*parts)``: a uint64 from the canonical JSON hash of the parts."""
    return int(content_sha256(list(parts))[:16], 16)


def research_seed(seed: int, shard: int, local: int) -> int:
    return derive_seed(seed, shard, local)


def mixed_seed(seed: int, shard: int, local: int) -> int:
    return derive_seed(seed, "mixed", shard, local)


def is_mixed(shard: int, local: int, every: int) -> bool:
    return every > 0 and (shard * SHARD_STRIDE + local) % every == every - 1


def shard_name(index: int) -> str:
    return f"shard-{index:06d}"


