#!/usr/bin/env python3
"""Label Standard training fights with a search teacher into distillation decision shards.

One call labels one chunk: train-split shards FIRST .. FIRST+COUNT-1 (from LABEL_SHARD_START up)
of the recipe's mixed arm, generated by ``generate_standard_shard`` with the Gym validator. Any
case outside the train split raises. Fights of the validation holdout runs (``validation_runs``)
are written to the ``validation`` shard series, all others to ``train``; each series gets one
shard per index, ``<series>/shard-<index:06d>``, written in index order while a rolling pool
plays every case of the chunk.

Per fight (shard s, local case l):
- research seed ``H(seed, s, l)`` and mixed-move stream ``H(seed, "mixed", s, l)``, where
  ``H(*parts)`` is the first 16 hex digits of ``content_sha256(list(parts))``; both are
  independent of chunking and scheduling;
- the fight is mixed when ``(s * 256 + l) % MIXED_EVERY == MIXED_EVERY - 1``: each move is then
  played by the ``--mixed-checkpoint`` player with probability 1/2 (a coin from the mixed stream),
  otherwise by the teacher. The teacher labels every decision; ``played`` records the move made.

Per decision: the compact frame (``snapshot_common``), the teacher's values, choice and root kind,
the public turn, and the decision's own ``RootContext``. Single-legal, refused and all-way-tie
roots get ``policy_ok`` false; a refused root stores choice -1 and plays the teacher's fallback.

At the fight's end: ``outcome``, ``hp_kept`` (``hp_after_cleanup / max_hp_start``, 0 on a death) and
``realised_v2`` (the ``resource-v2`` terminal value of the actual end, scored against each
decision's own root). Mixed and censored fights get no value targets. Delta 6: a fight that hits
the turn cap keeps its decisions from earlier public turns as policy-only rows when there are at
most KEPT_PREFIX_MAX of them (none otherwise); a fight that hits the fight cap keeps nothing.

Row r of every written shard with ``r % ROUNDTRIP_EVERY == 0`` (so row 0 of every non-empty
shard) is re-read from disk and must expand to the Gym's compact observation byte for byte (by
sha256 of the snapshot bytes taken in the worker); a mismatch is an error, as is any Gym fault and
any root refusal outside ``search_view.ROOT_REFUSAL_CLASSES``. ``chunk-manifest.json``
(deterministic: hashes, counts, provenance) is written last; ``report.json`` holds run-time
measurements. A failed call leaves no chunk manifest; rerun the chunk into a fresh --output under
``artifacts/development/neural-combat/distill/``. ``verify_chunk`` (stdlib only) checks a finished
chunk's files, counts and provenance against what the caller meant to produce.
"""

