# --- cases ---------------------------------------------------------------------------------

def _local_index(case: dict, shard: int) -> int:
    where = str(case.get("lineage_id", "")).rsplit(":", 1)[-1]
    shard_text, _, local_text = where.partition(".")
    if not (shard_text.isdigit() and local_text.isdigit()) or int(shard_text) != shard:
        raise ValueError(f"case {case.get('case_id')!r} has no lineage position in shard {shard}")
    return int(local_text)


def plan_jobs(shards, holdout, *, seed: int, mixed_every: int, case_limit: int | None = None) -> list[FightJob]:
    """One job per case, in shard then case order; any non-train case raises."""
    from spire_learn.neural.cases import environment_seed_for

    jobs = []
    for shard in shards:
        manifest = shard.manifest
        if manifest.get("split") != "train" or manifest.get("partition") != "train":
            raise ValueError(f"shard {shard.shard_index} is not a train-split shard")
        cases = list(manifest["cases"])
        for case in cases[:case_limit] if case_limit else cases:
            case = json_value(case)
            annotation = shard.annotations[case["entry"]["id"]]
            run_id = annotation["run_id"]
            if run_split(run_id) != "train":
                raise ValueError(f"case {case['case_id']!r} is from a {run_split(run_id)}-split run; "
                                 "only train-split runs are labelled")
            local = _local_index(case, shard.shard_index)
            ordinal = shard.shard_index * SHARD_STRIDE + local
            if case["environment_seed"] != environment_seed_for("train", replica=0, ordinal=ordinal):
                raise ValueError(f"case {case['case_id']!r} does not carry its train environment seed")
            jobs.append(FightJob(
                case=case, run_id=run_id, shard=shard.shard_index, local=local,
                series="validation" if run_id in holdout else "train",
                mixed=is_mixed(shard.shard_index, local, mixed_every),
                research_seed=research_seed(seed, shard.shard_index, local),
                mixed_seed=mixed_seed(seed, shard.shard_index, local)))
    return jobs


# --- one fight -----------------------------------------------------------------------------

def _root_kind(root: str) -> str:
    if root in ("searched", "single_legal"):
        return root
    if root not in ROOT_REFUSAL_CLASSES:
        raise RuntimeError(f"Unknown root class {root!r}: not a search root, a single legal action "
                           "or a known Gym refusal")
    return "refused"


def frame_digest(schema_fingerprint: str, tensors) -> str:
    """sha256 over a frame's fingerprint and every tensor's name, dtype, shape and bytes, in name order."""
    digest = sha256(schema_fingerprint.encode())
    for name in sorted(tensors):
        item = tensors[name]
        digest.update(f"\0{name}\0{item.dtype}\0{list(item.shape)}\0".encode())
        digest.update(item.data)
    return digest.hexdigest()


def _end_values(rule, view, records, final_observation, info, outcome):
    """(cleanup HP, realised_v2 per decision against its own root); raises without the end state needed.

    A death keeps nothing (cleanup HP 0, value -1); otherwise the observation's cleanup HP is required
    and must agree with the info's when the Gym reports both.
    """
    reward = entry.TERMINAL_REWARDS[outcome]
    cleanup = 0
    if outcome != "death":
        cleanup = view.cleanup_hp(final_observation)  # raises when the Gym left it unknown
        reported = info.get("hp_after_cleanup")
        if reported is not None and int(reported) != cleanup:
            raise RuntimeError("Terminal fight hp_after_cleanup differs between info and observation")
    return cleanup, [terminal_score(rule, record["context"], view, final_observation, reward, info)
                     for record in records]


def label_fight(env, job: FightJob, view, schema, turn_column, teacher, *, player=None) -> dict:
    """Play and label one fight; returns its stored rows ``(encoded arrays, labels, Gym frame digest)``."""
    from spire_learn.neural.distill_data import CHOICE_NONE, DecisionLabels, encode_decision
    from spire_learn.neural.snapshot import snapshot_common

    rule, _ = entry._value_options(teacher)
    if rule.name != "resource-v2":
        raise ValueError("distillation labels need a resource-v2 teacher")
    coin = None
    if job.mixed:
        if player is None:
            raise ValueError("a mixed fight needs the checkpoint player")
        coin = random.Random(job.mixed_seed)
        player.reseed(coin.getrandbits(63))
    pending: dict = {}
    records: list[dict] = []
    end: dict = {}

    def chooser(observation, legal, teacher_result, rng):
        frame = snapshot_common(observation, schema)
        by_player = coin is not None and coin.random() < 0.5
        pending.update(frame=frame, teacher=teacher_result, by_player=by_player)
        return player.act(frame, legal) if by_player else teacher_result[1]

    def observer(observation, decision, turn):
        frame, (root, choice, values, *_), by_player = (pending.pop(key) for key in ("frame", "teacher", "by_player"))
        legal = view.legal(observation)
        kind = _root_kind(root)
        ordered, samples, all_tie = None, 0, False
        if kind == "searched":
            if sorted(int(action) for action in values) != legal:
                raise RuntimeError("Searched root values do not cover the legal set")
            ordered = [float(values[str(action)][0]) for action in legal]
            samples = min(int(values[str(action)][1]) for action in legal)
            all_tie = len(set(ordered)) == 1
        records.append({
            "arrays": encode_decision(frame, schema),
            "digest": frame_digest(frame.schema_fingerprint, frame.tensors),
            "legal": legal, "values": ordered, "samples": samples,
            "choice": CHOICE_NONE if kind == "refused" else int(choice), "played": int(decision["choice"]),
            "root": kind, "refusal": root if kind == "refused" else None, "all_tie": all_tie,
            "policy_ok": kind == "searched" and not all_tie, "research_seed": decision["research_seed"],
            "turn": turn, "by_player": by_player,
            "context": RootContext.from_observation(view, observation, rule),
        })

    def finisher(final_observation, info, outcome, censor_reason):
        end.update(outcome=outcome, censor_reason=censor_reason)
        if censor_reason is None and not job.mixed and records:
            end["cleanup"], end["realised_v2"] = _end_values(rule, view, records, final_observation, info, outcome)

    fight, _ = entry.play_fight(env, job.case, view, turn_column, teacher, research_seed=job.research_seed,
                                max_steps=FIGHT_CAP, max_turn_actions=TURN_CAP,
                                chooser=chooser, observer=observer, finisher=finisher)
    censor = fight["censor_reason"]
    if censor == "step_cap":
        kept = []
    elif censor == "turn_cap":
        capped = records[-1]["turn"]
        prefix = [record for record in records if record["turn"] < capped]
        kept = prefix if len(prefix) <= KEPT_PREFIX_MAX else []
    else:
        kept = records
    value_ok = censor is None and not job.mixed
    outcome = _OUTCOME_LABELS.get(fight["outcome"], "none")
    hp_kept = end["cleanup"] / fight["max_hp_start"] if value_ok and records else math.nan
    realised = end.get("realised_v2", [math.nan] * len(records))
    position = {id(record): index for index, record in enumerate(records)}
    rows = []
    for record in kept:
        labels = DecisionLabels(
            legal=record["legal"], values=record["values"], samples=record["samples"], choice=record["choice"],
            played=record["played"], root=record["root"], outcome=outcome, hp_kept=hp_kept,
            realised_v2=realised[position[id(record)]] if value_ok else math.nan, value_ok=value_ok,
            policy_ok=record["policy_ok"], research_seed=record["research_seed"], case=(job.shard, job.local),
            run_id=job.run_id, turn=record["turn"])
        rows.append((record["arrays"], labels, record["digest"]))
    return {
        "shard": job.shard, "local": job.local, "series": job.series,
        "fight_type": "mixed" if job.mixed else "teacher", "outcome": fight["outcome"], "censor_reason": censor,
        "decisions": len(records), "dropped": len(records) - len(kept), "rows": rows,
        "roots": dict(Counter(record["root"] for record in kept)),
        "refusals": dict(Counter(record["refusal"] for record in kept if record["refusal"])),
        "all_tie": sum(record["all_tie"] for record in kept),
        "player_moves": sum(record["by_player"] for record in records),
        "cpu_seconds": fight["cpu_seconds"], "wall_seconds": fight["wall_seconds"],
    }


# --- workers -------------------------------------------------------------------------------

_SCHEMAS: dict = {}
_PLAYERS: dict = {}


def _schema_for(descriptor, revision, expected):
    from spire_learn.neural.schema import parse_combat_descriptor

    key = descriptor["fingerprint"]
    if key not in _SCHEMAS:
        _SCHEMAS[key] = parse_combat_descriptor(descriptor, revision=revision)
    schema = _SCHEMAS[key]
    if expected is not None and schema.schema_fingerprint != expected:
        raise RuntimeError("A fight's compact descriptor differs from the chunk's observation schema")
    return schema


def _player_for(context: LabelContext, schema):
    from spire_learn.neural.policy_player import CheckpointPlayer, standard_ff_identity

    key = (context.mixed_checkpoint, schema.schema_fingerprint)
    if key not in _PLAYERS:
        _PLAYERS[key] = CheckpointPlayer(
            context.mixed_checkpoint, schema, seed=0, model_config=MIXED_MODEL_CONFIG,
            expected_identity=standard_ff_identity(MIXED_MODEL_CONFIG, context.mixed_mapping))
    return _PLAYERS[key]


def _turn_column(descriptor) -> int:
    player = next(tensor for tensor in descriptor["tensors"] if tensor["key"] == "player")
    return [column["field"] for column in player["columns"]].index("turn")


def _label_job(item):
    job, context = item
    with entry._fight_env(job.case, "train") as (env, descriptor):
        schema = _schema_for(descriptor, context.gym_revision, context.schema_fingerprint)
        player = _player_for(context, schema) if job.mixed else None
        return label_fight(env, job, View(descriptor), schema, _turn_column(descriptor), context.teacher,
                           player=player)


class WorkerFault(RuntimeError):
    """A worker job's exception as plain, picklable fields (Gym fault classes cannot cross the pool)."""

    FIELDS = ("shard", "local", "run_id", "error_type", "error_message", "traceback_text")

    def __init__(self, shard, local, run_id, error_type, error_message, traceback_text):
        self.shard, self.local, self.run_id = shard, local, run_id
        self.error_type, self.error_message, self.traceback_text = error_type, error_message, traceback_text
        super().__init__(str(self))

    def __str__(self):
        return (f"label fault in shard {self.shard} local {self.local} run_id {self.run_id}: {self.error_type}: {self.error_message}\n"
                f"worker traceback:\n{self.traceback_text}")

    def __reduce__(self):
        return (type(self), tuple(getattr(self, name) for name in self.FIELDS))


def _guarded_label_job(item):
    """Run the job; re-raise any exception as a picklable WorkerFault naming the case."""
    try:
        return _label_job(item)
    except Exception as error:
        job = item[0]
        raise WorkerFault(job.shard, job.local, job.run_id, f"{type(error).__module__}.{type(error).__qualname__}",
                          str(error), traceback.format_exc()) from None


def _results(items, parallel):
    if parallel == 1:
        yield from map(_guarded_label_job, items)
        return
    pool = ProcessPoolExecutor(max_workers=parallel, mp_context=multiprocessing.get_context("spawn"))
    try:
        yield from pool.map(_guarded_label_job, items)
    finally:
        pool.shutdown(cancel_futures=True)


